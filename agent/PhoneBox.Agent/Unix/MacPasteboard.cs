using System.Runtime.InteropServices;

namespace PhoneBox.Agent;

/// <summary>
/// NSPasteboard through the Objective-C runtime, in this process: the bridge polls the change counter every 400 ms, and
/// spawning pbpaste or osascript that often would be slow (osascript takes seconds when the Mac is busy) and wasteful.
/// Every call runs inside its own autorelease pool because the callers are timer and request threads, which have none.
/// </summary>
internal sealed class MacPasteboard : ITextPasteboard
{
    private const string ObjC = "/usr/lib/libobjc.A.dylib";
    private const string AppKit = "/System/Library/Frameworks/AppKit.framework/AppKit";
    private const string PlainText = "public.utf8-plain-text";

    /// <summary>Types that password managers and the system add to what they copy; such an item is never shared.</summary>
    private static readonly string[] Withheld =
    [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ];

    [DllImport(ObjC)] private static extern nint objc_getClass(string name);
    [DllImport(ObjC)] private static extern nint sel_registerName(string name);
    [DllImport(ObjC)] private static extern nint objc_autoreleasePoolPush();
    [DllImport(ObjC)] private static extern void objc_autoreleasePoolPop(nint pool);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern nint Send(nint receiver, nint selector);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern nint Send(nint receiver, nint selector, nint a);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern nint SendAt(nint receiver, nint selector, nuint index);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] private static extern long SendLong(nint receiver, nint selector);
    [DllImport(ObjC, EntryPoint = "objc_msgSend")] [return: MarshalAs(UnmanagedType.I1)]
    private static extern bool SendBool(nint receiver, nint selector, nint a, nint b);

    private static readonly Lazy<bool> Loaded = new(() => NativeLibrary.TryLoad(AppKit, out _));
    private static nint Sel(string name) => sel_registerName(name);

    private readonly nint _pasteboard;

    /// <param name="name">Null for the general pasteboard (the real clipboard); a name for a private one, which tests use so
    /// they never touch what the owner copied.</param>
    public MacPasteboard(string? name = null)
    {
        if (!OperatingSystem.IsMacOS() || !Loaded.Value) throw new PlatformNotSupportedException("the macOS pasteboard needs macOS");
        var pool = objc_autoreleasePoolPush();
        try
        {
            var cls = objc_getClass("NSPasteboard");
            var pb = name is null ? Send(cls, Sel("generalPasteboard")) : Send(cls, Sel("pasteboardWithName:"), NSString(name));
            if (pb == 0) throw new InvalidOperationException("NSPasteboard is not available");
            _pasteboard = Send(pb, Sel("retain"));
        }
        finally { objc_autoreleasePoolPop(pool); }
    }

    public long ChangeCount
    {
        get
        {
            var pool = objc_autoreleasePoolPush();
            try { return SendLong(_pasteboard, Sel("changeCount")); }
            finally { objc_autoreleasePoolPop(pool); }
        }
    }

    public string? ReadShareableText()
    {
        var pool = objc_autoreleasePoolPush();
        try
        {
            var types = Send(_pasteboard, Sel("types"));
            if (types != 0)
            {
                var count = SendLong(types, Sel("count"));
                for (long i = 0; i < count; i++)
                    if (Managed(SendAt(types, Sel("objectAtIndex:"), (nuint)i)) is { } type && Array.IndexOf(Withheld, type) >= 0)
                        return null;
            }
            var text = Managed(Send(_pasteboard, Sel("stringForType:"), NSString(PlainText)));
            return string.IsNullOrEmpty(text) ? null : text;
        }
        finally { objc_autoreleasePoolPop(pool); }
    }

    public bool WriteText(string text)
    {
        var pool = objc_autoreleasePoolPush();
        try
        {
            SendLong(_pasteboard, Sel("clearContents"));
            return SendBool(_pasteboard, Sel("setString:forType:"), NSString(text), NSString(PlainText));
        }
        finally { objc_autoreleasePoolPop(pool); }
    }

    /// <summary>For tests: adds another type to the current item, the way a password manager marks what it copies.</summary>
    internal void DeclareExtraType(string uti)
    {
        var pool = objc_autoreleasePoolPush();
        try { SendBool(_pasteboard, Sel("setString:forType:"), NSString(""), NSString(uti)); }
        finally { objc_autoreleasePoolPop(pool); }
    }

    /// <summary>An autoreleased NSString; valid until the surrounding pool is popped.</summary>
    private static nint NSString(string value)
    {
        var utf8 = Marshal.StringToCoTaskMemUTF8(value);
        try { return Send(objc_getClass("NSString"), Sel("stringWithUTF8String:"), utf8); }
        finally { Marshal.FreeCoTaskMem(utf8); }
    }

    private static string? Managed(nint nsString) =>
        nsString == 0 ? null : Send(nsString, Sel("UTF8String")) is var chars and not 0 ? Marshal.PtrToStringUTF8(chars) : null;
}
